_CLASSIFICATION_VERY_STRONG = "VERY_STRONG"
_CLASSIFICATION_STRONG      = "STRONG"
_CLASSIFICATION_POSSIBLE    = "POSSIBLE"
_CLASSIFICATION_LOW         = "LOW"


