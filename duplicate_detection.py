"""
CarHunter v3.0 — Cross-Source Duplicate Detection
==================================================
Detects likely duplicate vehicle listings that appear on more than one
source (e.g. AutoScout24 and PKW.de) without performing any automatic
vehicle merge.

SAFETY CONTRACT
---------------
* Detection is read-only with respect to listings, vehicles,
  source_listings, source_snapshots, and the cars compatibility table.
* The only writes are to listing_duplicate_candidates.
* No Vehicle.vehicle_id is ever modified.
* No Listing is ever deleted or merged.
* VIN-based automatic resolution remains the sole auto-merge path
  (implemented separately in database.resolve_canonical_vehicle_links).

DESIGN
------
1. Blocking
   Candidate pairs are generated by matching on tight price + mileage
   bands (≤3 % price difference, ≤5 % + 1 000 km mileage difference)
   across listings from DIFFERENT sources.  Only ACTIVE listings are
   considered.

2. Scoring
   Each candidate pair is scored using explicit deterministic signals:

   VERY_STRONG  (≥85): only reachable with multiple strong signals
   STRONG       (≥60): consistent key fields
   POSSIBLE     (≥35): some overlapping fields
   LOW          (<35):  weak coincidence

3. Persistence
   Results are stored in listing_duplicate_candidates with stable
   pair ordering (min_id, max_id) to guarantee idempotency.
   Operator decisions (CONFIRMED_SAME / CONFIRMED_DIFFERENT / DISMISSED)
   are preserved on rescore.
"""

