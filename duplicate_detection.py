def _norm_drive(s: str | None) -> str:
    if not s:
        return ""
    return _DRIVE_MAP.get(s.lower().strip(), s.lower().strip())


_GEARBOX_MAP = {
    "automatik": "auto", "automatic": "auto", "auto": "auto",
    "dsg": "auto", "s tronic": "auto", "s-tronic": "auto",
    "tiptronic": "auto", "pdk": "auto", "cvt": "auto",
    "schaltgetriebe": "manual", "manual": "manual", "manuell": "manual",
}

def _norm_gearbox(s: str | None) -> str:
    if not s:
        return ""
    return _GEARBOX_MAP.get(s.lower().strip(), s.lower().strip())


def _token_similarity(a: str, b: str) -> float:
    """Jaccard similarity on word tokens."""
    if not a or not b:
        return 0.0
    ta = set(_norm_text(a).split())
    tb = set(_norm_text(b).split())
    if not ta or not tb:
        return 0.0
    intersection = ta & tb
    union = ta | tb
    return len(intersection) / len(union)


def _long_common_tokens(a: str, b: str) -> float:
    """Token overlap on words ≥5 chars — filters out common stop words."""
    if not a or not b:
        return 0.0
    ta = {w for w in _norm_text(a).split() if len(w) >= 5}
    tb = {w for w in _norm_text(b).split() if len(w) >= 5}
    if not ta or not tb:
        return 0.0
    return len(ta & tb) / max(len(ta), len(tb))


# ---------------------------------------------------------------------------
# Snapshot field extractor
# ---------------------------------------------------------------------------

def _get_snapshot_fields(listing_id: int, conn) -> dict[str, Any]:
    """
    Return merged extracted_fields for a listing, combining all snapshots
    so that detail fields present in an older snapshot are not lost if the
    latest snapshot is a summary-only re-scrape.
    Earlier snapshots are applied first (lowest precedence); later snapshots
    override, but only for non-empty values.
    """
    rows = conn.execute(
        """
        SELECT ss.extracted_fields
        FROM source_snapshots ss
        JOIN source_listings sl
          ON sl.source_id = ss.source_id
         AND sl.source_listing_id = ss.source_listing_id
        JOIN listings l ON l.source_listing_row_id = sl.id
        WHERE l.id = ?
        ORDER BY ss.id ASC
        """,
        (listing_id,),
    ).fetchall()
    merged: dict[str, Any] = {}
    for row in rows:
        if row and row[0]:
            try:
                fields = json.loads(row[0])
                for k, v in fields.items():
                    if v is not None and v != "" and v != [] and v != {}:
                        merged[k] = v
            except (ValueError, TypeError):
                pass
    return merged


def _listing_data(listing_row, snap: dict[str, Any]) -> dict[str, Any]:
    """
    Build the data dict used for scoring.

    TEMPORAL SAFETY RULE:
    Mutable fields that reflect current market state — price, mileage,
    seller — are taken EXCLUSIVELY from the listings table columns
    (current_price, current_mileage, current_seller).  Snapshot fields
    are never allowed to override these even if the snapshot is richer,
    because an older snapshot may reflect a different price/mileage/owner.

    Stable descriptive fields — title, year, colour, power, drivetrain,
    transmission, VIN, make, model, first_registration — may be enriched
    from historical snapshots because they do not change meaningfully
    across a vehicle's listing lifetime.
    """
    lid, source_id, source_listing_id, price, mileage, seller, description, options = listing_row

    # Prefer description; fall back to options JSON as comparable text
    desc_text = description or snap.get("description")
    if not desc_text and options:
        try:
            opts = json.loads(options) if isinstance(options, str) else options
            if isinstance(opts, list):
                desc_text = " ".join(str(o) for o in opts)
        except (ValueError, TypeError):
            desc_text = str(options)

    return {
        "id": lid,
        "source_id": source_id,
        "source_listing_id": source_listing_id,
        # ── MUTABLE (current state from listings table only) ───────────────
        "price": price,          # current_price — never from snapshot
        "mileage": mileage,      # current_mileage — never from snapshot
        "seller": seller,        # current_seller — never from snapshot
        # ── STABLE DESCRIPTIVE (snapshot enrichment allowed) ──────────────
        "description": desc_text,
        "options": options,
        "title": snap.get("title"),
        "year": snap.get("year"),
        "first_registration": snap.get("first_registration"),
        "colour": snap.get("colour") or snap.get("color"),
        "power_hp": snap.get("power_hp") or snap.get("hp"),
        "drivetrain": snap.get("drivetrain") or snap.get("drive"),
        "transmission": snap.get("transmission") or snap.get("gearbox"),
        "vin": snap.get("vin"),
        "make": snap.get("make"),
        "model": snap.get("model"),
    }


# ---------------------------------------------------------------------------
# Scoring
# ---------------------------------------------------------------------------

def score_pair(a: dict[str, Any], b: dict[str, Any]) -> dict[str, Any]:
    """
    Score a candidate pair and return a result dict with:
      score, classification, reasons (evidence), differences

    VIN VETO: conflicting VINs are an absolute veto for STRONG/VERY_STRONG
    regardless of all other signals.  The classification is capped at POSSIBLE
    and the score is zeroed when VINs conflict.
    """
    score = 0
    reasons: list[str] = []
    differences: list[str] = []
    vin_conflict = False

    # ── VIN check ──────────────────────────────────────────────────────────
    vin_a = (a.get("vin") or "").strip().upper()
    vin_b = (b.get("vin") or "").strip().upper()
    if vin_a and vin_b:
        if vin_a == vin_b:
            # VIN match is handled by ARCH-007 auto-merge; record as evidence.
            reasons.append("exact VIN match")
            score += 40
        else:
            vin_conflict = True
            differences.append(f"conflicting VIN: {vin_a} vs {vin_b}")

    # ── Price ───────────────────────────────────────────────────────────────
    pa, pb = a.get("price"), b.get("price")
    if pa and pb:
        diff_pct = abs(pa - pb) / max(pa, pb)
        if diff_pct <= 0.01:
            score += _W_PRICE_EXACT
            reasons.append(f"exact price: {pa}")
        elif diff_pct <= 0.05:
            score += _W_PRICE_EXACT // 2
            reasons.append(f"very close price: {pa} vs {pb}")
        else:
            differences.append(f"price difference: {pa} vs {pb} ({diff_pct:.0%})")

    # ── Mileage ─────────────────────────────────────────────────────────────
    ma = a.get("mileage")
    mb = b.get("mileage")
    if ma and mb:
        diff_km = abs(ma - mb)
        diff_pct = diff_km / max(ma, mb)
        if diff_km <= 500 or diff_pct <= 0.02:
            score += _W_MILEAGE_EXACT
            reasons.append(f"exact mileage: {ma} km")
        elif diff_pct <= 0.05:
            score += _W_MILEAGE_EXACT // 2
            reasons.append(f"close mileage: {ma} vs {mb} km")
        else:
            differences.append(f"mileage difference: {ma} vs {mb} km ({diff_pct:.0%})")

    # ── Seller ──────────────────────────────────────────────────────────────
    sa = _norm_seller(a.get("seller"))
    sb = _norm_seller(b.get("seller"))
    if sa and sb:
        sim = _token_similarity(sa, sb)
        if sim >= 0.70:
            score += _W_SELLER_MATCH
            reasons.append(f"same seller: {a.get('seller')!r}")
        elif sim >= 0.40:
            score += _W_SELLER_MATCH // 2
            reasons.append("similar seller name")
        else:
            score += _PENALTY_SELLER_NEG
            differences.append(f"different seller: {a.get('seller')!r} vs {b.get('seller')!r}")

    # ── Registration year ───────────────────────────────────────────────────
    ya = _reg_year(a)
    yb = _reg_year(b)
    if ya and yb:
        if ya == yb:
            score += _W_REG_YEAR
            reasons.append(f"same registration year: {ya}")
        else:
            score += _PENALTY_REG_MISMATCH
            differences.append(f"different year: {ya} vs {yb}")

    # ── Title similarity ────────────────────────────────────────────────────
    ta, tb = a.get("title"), b.get("title")
    if ta and tb:
        # Use token-overlap but also reward when the shorter title's tokens
        # are a subset of the longer title (abbreviated form).
        ta_norm = set(_norm_text(ta).split())
        tb_norm = set(_norm_text(tb).split())
        shorter, longer = (ta_norm, tb_norm) if len(ta_norm) <= len(tb_norm) else (tb_norm, ta_norm)
        containment = len(shorter & longer) / len(shorter) if shorter else 0.0
        jaccard = len(ta_norm & tb_norm) / len(ta_norm | tb_norm) if (ta_norm | tb_norm) else 0.0
        sim = max(containment, jaccard)
        if sim >= 0.85:
            score += _W_TITLE_HIGH
            reasons.append(f"high title similarity ({sim:.0%}): {ta!r}")
        elif sim >= 0.60:
            score += _W_TITLE_MOD
            reasons.append(f"moderate title similarity ({sim:.0%})")
        else:
            differences.append(f"low title similarity ({sim:.0%}): {ta!r} vs {tb!r}")

    # ── Description overlap ─────────────────────────────────────────────────
    da, db = a.get("description"), b.get("description")
    if da and db and len(da) > 100 and len(db) > 100:
        sim = _long_common_tokens(da, db)
        if sim >= 0.70:
            score += _W_DESC_HIGH
            reasons.append(f"high description/equipment overlap ({sim:.0%})")
        elif sim >= 0.40:
            score += _W_DESC_HIGH // 2
            reasons.append(f"moderate description overlap ({sim:.0%})")

    # ── Power ───────────────────────────────────────────────────────────────
    hpa = _to_int(a.get("power_hp"))
    hpb = _to_int(b.get("power_hp"))
    if hpa and hpb:
        diff_pct = abs(hpa - hpb) / max(hpa, hpb)
        if diff_pct <= 0.05:
            score += _W_POWER_MATCH
            reasons.append(f"same power: {hpa} hp")
        elif diff_pct > 0.15:
            score += _PENALTY_POWER_CONFLICT
            differences.append(f"different power: {hpa} vs {hpb} hp")

    # ── Transmission ────────────────────────────────────────────────────────
    ga = _norm_gearbox(a.get("transmission"))
    gb = _norm_gearbox(b.get("transmission"))
    if ga and gb:
        if ga == gb:
            score += _W_TRANSMISSION
            reasons.append(f"same transmission: {ga}")
        else:
            differences.append(f"different transmission: {ga} vs {gb}")

    # ── Drivetrain ──────────────────────────────────────────────────────────
    dra = _norm_drive(a.get("drivetrain"))
    drb = _norm_drive(b.get("drivetrain"))
    if dra and drb:
        if dra == drb:
            score += _W_DRIVETRAIN
            reasons.append(f"same drivetrain: {dra}")
        else:
            differences.append(f"different drivetrain: {dra} vs {drb}")

    # ── Colour ──────────────────────────────────────────────────────────────
    ca = _norm_colour(a.get("colour"))
    cb = _norm_colour(b.get("colour"))
    if ca and cb:
        if ca == cb:
            score += _W_COLOUR_MATCH
            reasons.append(f"same colour: {ca}")
        else:
            differences.append(f"different colour: {ca} vs {cb}")

    score = max(0, min(100, score))

    # ── VIN conflict hard veto ──────────────────────────────────────────────
    # Conflicting VINs mean these cannot be the same physical vehicle.
    # Cap classification at POSSIBLE and zero the score, regardless of
    # how many other signals matched.
    if vin_conflict:
        score = min(score, 30)
        classification = _CLASSIFICATION_POSSIBLE if score >= 35 else _CLASSIFICATION_LOW
        differences.insert(0, "VIN_CONFLICT_VETO: capped at POSSIBLE")
    else:
        classification = _classify(score)

    return {
        "score": score,
        "classification": classification,
        "reasons": reasons,
        "differences": differences,
    }


def _reg_year(d: dict) -> int | None:
    yr = d.get("year")
    if yr:
        try:
            return int(str(yr)[:4])
        except (ValueError, TypeError):
            pass
    reg = d.get("first_registration") or ""
    m = re.match(r"(\d{4})", str(reg))
    if m:
        return int(m.group(1))
    return None


def _to_int(v) -> int | None:
    try:
        return int(v) if v is not None else None
    except (ValueError, TypeError):
        return None


def _classify(score: int) -> str:
    if score >= 85:
        return _CLASSIFICATION_VERY_STRONG
    if score >= 60:
        return _CLASSIFICATION_STRONG
    if score >= 35:
        return _CLASSIFICATION_POSSIBLE
    return _CLASSIFICATION_LOW


