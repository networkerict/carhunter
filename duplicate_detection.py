# Persistence
# ---------------------------------------------------------------------------

def ensure_schema(conn) -> None:
    """Create detection tables and indexes if they do not exist.

    Does NOT commit; the caller controls the transaction.  When called
    from run_detection with an internally-owned connection the commit
    happens naturally; when called with an external connection the caller
    remains in control.
    """
    for stmt in _DDL.strip().split(";"):
        stmt = stmt.strip()
        if stmt:
            conn.execute(stmt)


def upsert_candidate(
    conn,
    lid_a: int,
    lid_b: int,
    result: dict[str, Any],
    *,
    run_ts: str,
) -> None:
    """
    Insert or update a candidate row.  Existing operator status is preserved
    on update.  Stable ordering: lid_a < lid_b always.

    run_ts is the ISO timestamp of the current detection run, stored in
    last_evaluated_at so stale detection can identify rows not seen in
    a subsequent run.
    """
    a, b = min(lid_a, lid_b), max(lid_a, lid_b)
    now = datetime.now().isoformat()
    evidence = json.dumps(result["reasons"])
    differences = json.dumps(result["differences"])
    score = result["score"]
    classification = result["classification"]

    existing = conn.execute(
        "SELECT id, status FROM listing_duplicate_candidates WHERE listing_id_a=? AND listing_id_b=?",
        (a, b),
    ).fetchone()

    if existing:
        # Preserve operator status; update scoring and mark as evaluated
        conn.execute(
            """
            UPDATE listing_duplicate_candidates
            SET score=?, classification=?, evidence=?, differences=?,
                last_evaluated_at=?, updated_at=?,
                status = CASE
                    WHEN status = 'STALE' THEN 'OPEN'
                    ELSE status
                END
            WHERE listing_id_a=? AND listing_id_b=?
            """,
            (score, classification, evidence, differences, run_ts, now, a, b),
        )
    else:
        conn.execute(
            """
            INSERT INTO listing_duplicate_candidates
            (listing_id_a, listing_id_b, score, classification, evidence, differences,
             status, last_evaluated_at, created_at, updated_at)
            VALUES (?,?,?,?,?,?,'OPEN',?,?,?)
            """,
            (a, b, score, classification, evidence, differences, run_ts, now, now),
        )


