def run_detection(*, dry_run: bool = False, conn=None) -> dict[str, Any]:
    """
    Run the full detection pipeline.

    dry_run=True: score candidates but do not write to the database.

    Returns summary counts by classification and a list of top candidates.
    """
    should_close = conn is None
    conn = conn or database.get_connection()

    try:
        ensure_schema(conn)
        pairs = generate_candidates(conn)
        run_ts = datetime.now().isoformat()
        evaluated_pairs: set[tuple[int, int]] = set()

        results: list[dict] = []
        for a_data, b_data in pairs:
            result = score_pair(a_data, b_data)
            result["listing_id_a"] = a_data["id"]
            result["listing_id_b"] = b_data["id"]
            result["source_listing_id_a"] = a_data["source_listing_id"]
            result["source_listing_id_b"] = b_data["source_listing_id"]
            results.append(result)

            if not dry_run:
                upsert_candidate(conn, a_data["id"], b_data["id"], result, run_ts=run_ts)
                pair_key = (min(a_data["id"], b_data["id"]), max(a_data["id"], b_data["id"]))
                evaluated_pairs.add(pair_key)

        if not dry_run:
            # Mark OPEN pairs not seen in this run as STALE.
            # Preserves CONFIRMED_SAME / CONFIRMED_DIFFERENT / DISMISSED.
            if evaluated_pairs:
                placeholders = ",".join("(?,?)" for _ in evaluated_pairs)
                params: list = []
                for pa, pb in evaluated_pairs:
                    params.extend([pa, pb])
                conn.execute(
                    f"""
                    UPDATE listing_duplicate_candidates
                    SET status = 'STALE', updated_at = ?
                    WHERE status = 'OPEN'
                      AND (listing_id_a, listing_id_b) NOT IN ({placeholders})
                    """,
                    [run_ts] + params,
                )
            else:
                # No candidates at all — mark every OPEN row stale
                conn.execute(
                    "UPDATE listing_duplicate_candidates SET status='STALE', updated_at=? WHERE status='OPEN'",
                    (run_ts,),
                )
            conn.commit()

        by_class: dict[str, int] = {}
        for r in results:
            by_class[r["classification"]] = by_class.get(r["classification"], 0) + 1

        top_10 = sorted(results, key=lambda x: x["score"], reverse=True)[:10]

        return {
            "total_candidates": len(results),
            "by_classification": by_class,
            "top_candidates": top_10,
        }

    finally:
        if should_close:
            conn.close()


def score_listing_pair(listing_id_a: int, listing_id_b: int, *, conn=None) -> dict[str, Any]:
    """Score a single explicit listing pair and return the result dict."""
    should_close = conn is None
    conn = conn or database.get_connection()
    try:
        def _fetch(lid):
            row = conn.execute(
                "SELECT id, source_id, source_listing_id, current_price, current_mileage, "
                "current_seller, current_description, current_options FROM listings WHERE id=?",
                (lid,),
            ).fetchone()
            if row is None:
                raise ValueError(f"listing {lid} not found")
            snap = _get_snapshot_fields(lid, conn)
            return _listing_data(row, snap)

        a_data = _fetch(listing_id_a)
        b_data = _fetch(listing_id_b)
        return score_pair(a_data, b_data)
    finally:
        if should_close:
            conn.close()


