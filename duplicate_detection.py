_DDL = """
CREATE TABLE IF NOT EXISTS listing_duplicate_candidates (
    id                INTEGER PRIMARY KEY AUTOINCREMENT,
    listing_id_a      INTEGER NOT NULL,
    listing_id_b      INTEGER NOT NULL,
    score             INTEGER NOT NULL,
    classification    TEXT NOT NULL,
    evidence          TEXT NOT NULL DEFAULT '[]',
    differences       TEXT NOT NULL DEFAULT '[]',
    status            TEXT NOT NULL DEFAULT 'OPEN',
    last_evaluated_at TEXT,
    created_at        TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(listing_id_a, listing_id_b),
    FOREIGN KEY (listing_id_a) REFERENCES listings(id),
    FOREIGN KEY (listing_id_b) REFERENCES listings(id),
    CHECK (listing_id_a < listing_id_b),
    CHECK (status IN ('OPEN','CONFIRMED_SAME','CONFIRMED_DIFFERENT','DISMISSED','STALE'))
);
CREATE INDEX IF NOT EXISTS idx_ldc_status
    ON listing_duplicate_candidates(status);
CREATE INDEX IF NOT EXISTS idx_ldc_classification
    ON listing_duplicate_candidates(classification, score DESC);
"""

# ---------------------------------------------------------------------------
# Scoring weights
# ---------------------------------------------------------------------------

_W_PRICE_EXACT    = 20   # price within 1%
_W_MILEAGE_EXACT  = 20   # mileage within 2% or 500 km
_W_SELLER_MATCH   = 20   # normalised dealer name match
_W_REG_YEAR       = 10   # same registration year
_W_TITLE_HIGH     = 10   # normalised title similarity ≥ 0.85
_W_TITLE_MOD      =  5   # normalised title similarity ≥ 0.60
_W_DESC_HIGH      =  8   # long shared description tokens ≥ 0.70
_W_POWER_MATCH    =  5   # same power (hp) within 5%
_W_TRANSMISSION   =  3   # same gearbox family
_W_DRIVETRAIN     =  3   # same drive type
_W_COLOUR_MATCH   =  2   # same colour family

_PENALTY_VIN_CONFLICT   = -80   # conflicting VINs → never strong
_PENALTY_REG_MISMATCH   = -15   # different reg year
_PENALTY_POWER_CONFLICT = -10   # clearly different engine (>15% difference)
_PENALTY_SELLER_NEG     =  -8   # explicitly different seller (when both known)

_CLASSIFICATION_VERY_STRONG = "VERY_STRONG"
_CLASSIFICATION_STRONG      = "STRONG"
_CLASSIFICATION_POSSIBLE    = "POSSIBLE"
_CLASSIFICATION_LOW         = "LOW"


# ---------------------------------------------------------------------------
# Normalisation helpers
# ---------------------------------------------------------------------------

def _norm_text(s: str | None) -> str:
    if not s:
        return ""
    s = unicodedata.normalize("NFC", str(s))
    s = s.upper()
    s = re.sub(r"[^\w\s]", " ", s)
    s = re.sub(r"\s+", " ", s).strip()
    return s


_LEGAL_SUFFIXES = re.compile(
    r"\b(GMBH|CO|KG|AG|GBMR|MBHG|UND|&|E\.K\.|EK|SARL|SAS|SRL|BV)\b",
    re.IGNORECASE,
)

def _norm_seller(s: str | None) -> str:
    if not s:
        return ""
    # Extract companyName from Python dict repr or JSON string
    # e.g. "{'companyName': 'Autocenter Neuss ...'}"
    cn_match = re.search(r"['\"]?companyName['\"]?\s*[:=]\s*['\"]([^'\"]+)['\"]", s)
    if cn_match:
        s = cn_match.group(1)
    s = _norm_text(s)
    s = _LEGAL_SUFFIXES.sub(" ", s)
    s = re.sub(r"\s+", " ", s).strip()
    return s


