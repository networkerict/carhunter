_CANDIDATE_QUERY = """
SELECT
    a.id, a.source_id, a.source_listing_id, a.current_price, a.current_mileage,
    a.current_seller, a.current_description, a.current_options,
    b.id, b.source_id, b.source_listing_id, b.current_price, b.current_mileage,
    b.current_seller, b.current_description, b.current_options
FROM listings a
JOIN listings b ON b.id > a.id
WHERE a.source_id != b.source_id
  AND a.availability = 'ACTIVE'
  AND b.availability = 'ACTIVE'
  AND a.current_price IS NOT NULL
  AND b.current_price IS NOT NULL
  AND ABS(CAST(a.current_price AS REAL) - CAST(b.current_price AS REAL))
      <= (a.current_price * 0.03 + 200)
  AND (
    a.current_mileage IS NULL
    OR b.current_mileage IS NULL
    OR ABS(CAST(a.current_mileage AS REAL) - CAST(b.current_mileage AS REAL))
       <= (a.current_mileage * 0.05 + 1000)
  )
"""


def generate_candidates(conn) -> list[tuple[dict, dict]]:
    """
    Return (listing_a_data, listing_b_data) pairs from different sources
    that pass the price + mileage blocking filter.
    """
    rows = conn.execute(_CANDIDATE_QUERY).fetchall()
    pairs = []
    for row in rows:
        a_row = row[:8]
        b_row = row[8:]
        snap_a = _get_snapshot_fields(a_row[0], conn)
        snap_b = _get_snapshot_fields(b_row[0], conn)
        pairs.append((_listing_data(a_row, snap_a), _listing_data(b_row, snap_b)))
    return pairs


